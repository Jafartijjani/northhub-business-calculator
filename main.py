
# Northhub Business Calculator
# A beginner Python project

business_name = "Northhub"
product_price = 15000
units_sold = 30

# Calculate total revenue
total_revenue = product_price * units_sold

# Calculate business profit
operating_expenses = 250000
total_profit = total_revenue - operating_expenses

# Check whether the revenue target was reached
check_revenue = total_revenue >= 400000

# Display business performance
print(business_name)
print(total_revenue)
print(total_profit)
print(check_revenue)
